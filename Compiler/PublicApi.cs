/// <summary>Options for a Kickstart-compatible ROM image.</summary>
public sealed record KickstartRomOutputOptions
{
	/// <summary>ROM size. Version one accepts 256 KiB or 512 KiB.</summary>
	public int Size { get; init; } = 512 * 1024;

	/// <summary>Initial supervisor stack pointer copied into reset vector zero.</summary>
	public uint InitialStackPointer { get; init; } = 0x0008_0000;

	/// <summary>Byte used for unused ROM space.</summary>
	public byte FillByte { get; init; } = 0xFF;

	/// <summary>
	/// Optional physical base. Zero selects the standard top-of-24-bit-space address
	/// derived from <see cref="Size"/>.
	/// </summary>
	public uint BaseAddress { get; init; }
}

/// <summary>Options for runtime-managed heap backends.</summary>
public sealed record M68kHeapOptions
{
	/// <summary>
	/// Start address for the compiler runtime's managed pool. Zero means
