/// <summary>Well-known hooks used by generated managed-runtime operations.</summary>
public static class M68kRuntimeImports
{
	/// <summary>Target marker enabling the built-in Amiga unhandled-exception requester.</summary>
	public const string AmigaUnhandledExceptionRequester =
		"__c68k_amiga_unhandled_exception_requester";

	/// <summary>Target marker enabling an Exec-owned arena for the built-in managed pool.</summary>
	public const string AmigaManagedPoolArena =
		"__c68k_amiga_managed_pool_arena";

	/// <summary>
	/// Allocates a zero-filled object block. The requested byte count is passed in
	/// D0 and the address is returned in D0.
	/// </summary>
	public const string Allocate = "__c68k_alloc";

	/// <summary>Non-returning handler used for null, bounds, and runtime failures.</summary>
	public const string Fail = "__c68k_fail";

	/// <summary>
	/// Optional last-chance exception hook. A0 contains the exception object and
	/// D0 contains the compiler runtime reason code. Returning continues to the
	/// target's unhandled-exception action.
	/// </summary>
	public const string UnhandledException = "__c68k_unhandled_exception";

	/// <summary>
	/// Explicitly releases a managed allocation slot. The address of a four-byte
	/// reference slot is passed in A0. Runtime code may free
	/// the allocation and should clear the slot to zero.
	/// </summary>
	public const string Dispose = "__c68k_dispose";

	/// <summary>Initializes a linked managed runtime before the managed entry point.</summary>
	public const string GcInit = "__c68k_gc_init";

	/// <summary>
	/// Runs an explicit managed collection cycle. D0 contains the address of the
	/// suspended return-PC slot, D1 the resume PC, A0 the generated method table,
	/// and A1 the static-root table.
	/// </summary>
	public const string GcCollect = "__c68k_gc_collect";

	/// <summary>Returns the runtime's approximate stale-pressure byte count.</summary>
	public const string GcGetStaleBytes = "__c68k_gc_get_stale_bytes";

	/// <summary>Returns the runtime's approximate stale-pressure block count.</summary>
	public const string GcGetStaleBlocks = "__c68k_gc_get_stale_blocks";

	/// <summary>Shuts down a linked managed runtime after the managed entry point.</summary>
	public const string GcShutdown = "__c68k_gc_shutdown";
}

