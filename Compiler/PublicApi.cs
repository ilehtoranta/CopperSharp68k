using System.Collections.ObjectModel;

namespace CopperSharp.Compiler;

/// <summary>Motorola CPU selected for generated code.</summary>
public enum M68kCpuTarget
{
	M68000,
	M68020,
	M68040,
	M68060
}

/// <summary>Floating-point implementation selected for generated code.</summary>
public enum M68kFloatingPointMode
{
	/// <summary>Reject managed floating-point values and emit no FPU instructions.</summary>
	Disabled,

	/// <summary>Use the integrated MC68040/MC68060 floating-point unit.</summary>
	M68040,

	/// <summary>Use an external MC68882 coprocessor with an MC68020 host CPU.</summary>
	M68882,

	/// <summary>Use the compiler's bundled integer-only CopperFloat runtime.</summary>
	SoftFloat
}

/// <summary>Policy for using the memory-writing <c>CLR</c> instruction.</summary>
public enum M68kClrPolicy
{
	/// <summary>
	/// Use CLR for isolated compiler-owned clears where materializing zero is not
	/// faster, and for general memory on CPUs without MC68000 read-before-write.
	/// </summary>
	Auto = 0,

	/// <summary>Use CLR even for MC68000-compatible targets.</summary>
	Always = 2
}

/// <summary>Container generated by the linker.</summary>
public enum M68kOutputFormat
{
	Hunk,
	KickstartRom,
	Assembly
}

/// <summary>High-level runtime assumptions selected for the generated image.</summary>
public enum M68kRuntimeProfile
{
	/// <summary>No post-entry lifetime or shutdown contract is assumed.</summary>
	Freestanding,

	/// <summary>
	/// The selected entry is invoked once as an application and its private
	/// image storage becomes unobservable when the entry terminates.
	/// </summary>
	Application,

	/// <summary>The generated image is persistent and may be entered again.</summary>
	Rom
}

/// <summary>Managed heap policy used by generated allocation instructions.</summary>
public enum M68kMemoryManagement
{
	None,
	ExternalAllocator,
	BumpAllocator,
	ManagedPoolMarkSweepGc,
	ExecPoolMarkSweepGc,
}

/// <summary>When a linked managed runtime should run mark/sweep collection.</summary>
public enum M68kGcSweepStrategy
{
	OnDemand,
	OnAllocationFailure,
	EveryAllocation,
	TelemetryTriggered
}

/// <summary>Managed exception behavior selected for generated code.</summary>
public enum M68kExceptionMode
{
	/// <summary>Use the table-driven managed exception runtime.</summary>
	Full,

	/// <summary>Preserve the legacy non-returning fault behavior.</summary>
	Yolo
}

/// <summary>Physical 68k register used by an imported or exported ABI.</summary>
public enum M68kRegister
{
	D0,
	D1,
	D2,
	D3,
	D4,
	D5,
	D6,
	D7,
	A0,
	A1,
	A2,
	A3,
	A4,
	A5,
	A6
}

/// <summary>Physical floating-point register used by a native FPU ABI.</summary>
public enum M68kFpuRegister
{
	FP0,
	FP1,
	FP2,
	FP3,
	FP4,
	FP5,
	FP6,
	FP7
}

/// <summary>How a platform extension supplies a base register for an external call.</summary>
public enum M68kExternalBaseSource
{
	CachedPointer,
	WritableSlot,
	Immediate
}

/// <summary>How an external call reports a managed failure.</summary>
public enum M68kExternalExceptionPolicy
{
	/// <summary>The call has no compiler-visible exception status.</summary>
	None,

	/// <summary>A nonzero value in the configured status register raises.</summary>
	NonZeroStatus
}

/// <summary>A decoded metadata attribute supplied to an optional platform resolver.</summary>
public sealed record M68kMetadataAttribute(
	string TypeName,
	IReadOnlyList<object?> FixedArguments);

/// <summary>Architecture-neutral metadata for an external method declaration.</summary>
public sealed record M68kExternalMethod(
	string AssemblyName,
	string DisplayName,
	string DeclaringTypeName,
	string Name,
	bool IsStatic,
	IReadOnlyList<M68kMetadataAttribute> DeclaringTypeAttributes,
	IReadOnlyList<M68kMetadataAttribute> MethodAttributes,
	IReadOnlyList<IReadOnlyList<M68kMetadataAttribute>> ParameterAttributes,
	IReadOnlyList<M68kMetadataAttribute> ReturnAttributes);

/// <summary>Describes one base-relative external call without platform-specific terminology.</summary>
public sealed record M68kExternalCallConvention(
	string Identity,
	M68kExternalBaseSource BaseSource,
	M68kRegister BaseRegister,
	short Displacement,
	M68kRegister? CacheRegister = null,
	uint SourceAddress = 0,
	uint InitialValue = 0,
	string? SlotSymbol = null,
	IReadOnlyList<M68kRegister>? ParameterRegisters = null,
	M68kRegister ReturnRegister = M68kRegister.D0,
	M68kExternalExceptionPolicy ExceptionPolicy = M68kExternalExceptionPolicy.None,
	M68kRegister? ExceptionStatusRegister = null);

/// <summary>Optional target-platform metadata and call-convention resolver.</summary>
public interface IM68kExternalCallResolver
{
	bool TryResolve(
		M68kExternalMethod method,
		out M68kExternalCallConvention convention);
}

/// <summary>Well-known hooks used by generated managed-runtime operations.</summary>
public static class M68kRuntimeImports
{
	/// <summary>Target marker enabling the built-in Amiga unhandled-exception requester.</summary>
	public const string AmigaUnhandledExceptionRequester =
		"__c68k_amiga_unhandled_exception_requester";

	/// <summary>Target marker enabling an Exec-owned arena for the built-in managed pool.</summary>
	public const string AmigaManagedPoolArena =
		"__c68k_amiga_managed_pool_arena";

	/// <summary>
	/// Allocates a zero-filled object block. The requested byte count is passed in
	/// D0 and the address is returned in D0.
	/// </summary>
	public const string Allocate = "__c68k_alloc";

	/// <summary>Non-returning handler used for null, bounds, and runtime failures.</summary>
	public const string Fail = "__c68k_fail";

	/// <summary>
	/// Optional last-chance exception hook. A0 contains the exception object and
	/// D0 contains the compiler runtime reason code. Returning continues to the
	/// target's unhandled-exception action.
	/// </summary>
	public const string UnhandledException = "__c68k_unhandled_exception";

	/// <summary>
	/// Explicitly releases a managed allocation slot. The address of a four-byte
	/// reference slot is passed in A0. Runtime code may free
	/// the allocation and should clear the slot to zero.
	/// </summary>
	public const string Dispose = "__c68k_dispose";

	/// <summary>Initializes a linked managed runtime before the managed entry point.</summary>
	public const string GcInit = "__c68k_gc_init";

	/// <summary>
	/// Runs an explicit managed collection cycle. D0 contains the address of the
	/// suspended return-PC slot, D1 the resume PC, A0 the generated method table,
	/// and A1 the static-root table.
	/// </summary>
	public const string GcCollect = "__c68k_gc_collect";

	/// <summary>Returns the runtime's approximate stale-pressure byte count.</summary>
	public const string GcGetStaleBytes = "__c68k_gc_get_stale_bytes";

	/// <summary>Returns the runtime's approximate stale-pressure block count.</summary>
	public const string GcGetStaleBlocks = "__c68k_gc_get_stale_blocks";

	/// <summary>Shuts down a linked managed runtime after the managed entry point.</summary>
	public const string GcShutdown = "__c68k_gc_shutdown";
}

