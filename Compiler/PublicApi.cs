/// <summary>Closed-world compilation request.</summary>
public sealed record M68kCompilationRequest
{
	public required string AssemblyPath { get; init; }

	/// <summary>
	/// Additional managed assemblies whose IL method bodies may enter the closed-world
	/// compilation graph. Other references remain metadata-only platform dependencies.
	/// </summary>
	public IReadOnlyList<string> ManagedAssemblyPaths { get; init; } = Array.Empty<string>();

	/// <summary>
	/// Optional pinned framework implementation pack. Implementation assemblies
	/// are isolated from <see cref="ManagedAssemblyPaths"/> and never become
	/// general managed-reference candidates.
	/// </summary>
	public M68kFrameworkImplementationPackOptions? FrameworkImplementationPack { get; init; }

	/// <summary>
	/// Target-managed lifecycle hooks. Hooks are pay-for-play and run only for
	/// <see cref="M68kRuntimeProfile.Application"/> when their required framework
	/// feature is reachable. Initialization follows declaration order; shutdown
	/// runs in reverse order and must be idempotent and non-throwing.
	/// </summary>
	public IReadOnlyList<M68kManagedLifecycleHook> ManagedLifecycleHooks { get; init; } =
		Array.Empty<M68kManagedLifecycleHook>();

	/// <summary>
	/// Target-package identity written to the linker map. Platform wrappers set
	/// this value; direct compiler use falls back to the generic compiler target.
	/// </summary>
	public M68kTargetContract? TargetContract { get; init; }

	/// <summary>
	/// Entry selector in <c>Namespace.Type::Method</c> form. When omitted, exactly one
	/// method carrying <see cref="M68kEntryPointAttribute"/> must exist.
	/// </summary>
	public string? EntryPoint { get; init; }

	/// <summary>
	/// Optional closed-world export allowlist. <see langword="null"/> preserves the
	/// historical behavior where every <see cref="M68kExportAttribute"/> in the
	/// primary assembly is emitted and seeded as a reachability root. An empty list
	/// emits no exports; otherwise only the named exports are emitted and rooted.
	/// Export declarations outside this list remain metadata but cannot be resolved
	/// by <c>APTR.ExportAddress</c> in this compilation.
	/// </summary>
	public IReadOnlyList<string>? IncludedExportNames { get; init; }

	public M68kCpuTarget Cpu { get; init; } = M68kCpuTarget.M68000;

	/// <summary>
	/// Selects native FPU or bundled software floating-point code generation.
	/// Disabled preserves the historical integer-only compiler behavior.
	/// </summary>
	public M68kFloatingPointMode FloatingPoint { get; init; } =
		M68kFloatingPointMode.Disabled;

	/// <summary>
	/// Controls memory clears. Auto accounts for the MC68000 CLR read cycle: it
	/// reuses an available zero register with MOVE, permits isolated CLR clears of
	/// compiler-owned memory when MOVEQ plus MOVE would not be faster, and enables
	/// CLR for general memory on MC68020 and newer targets. Always explicitly opts
	/// MC68000-compatible general memory into CLR's read-before-write behavior.
	/// </summary>
	public M68kClrPolicy ClrPolicy { get; init; } = M68kClrPolicy.Auto;

	/// <summary>
	/// Controls whether whole-image peephole rewriting runs to a fixed point or
	/// uses the deterministic large-graph budget. FixedPoint preserves historical
	/// output; Bounded preserves program semantics while guaranteeing finite work.
	/// </summary>
	public M68kPeepholeOptimizationMode PeepholeOptimization { get; init; } =
		M68kPeepholeOptimizationMode.FixedPoint;

	public M68kOutputFormat OutputFormat { get; init; } = M68kOutputFormat.Hunk;

	public M68kRuntimeProfile RuntimeProfile { get; init; } =
		M68kRuntimeProfile.Freestanding;

	/// <summary>
	/// Selects managed exception behavior. Full mode is the default; YOLO is an
	/// explicit compatibility mode for images that retain fatal runtime faults.
	/// </summary>
	public M68kExceptionMode ExceptionMode { get; init; } = M68kExceptionMode.Full;

	/// <summary>
	/// Managed heap policy. When omitted, ROM profile uses no managed heap and
	/// other profiles use the external <see cref="M68kRuntimeImports.Allocate"/>
	/// hook.
	/// </summary>
	public M68kMemoryManagement? MemoryManagement { get; init; }

	/// <summary>
	/// GC sweep trigger. When omitted, GC backends use
	/// <see cref="M68kGcSweepStrategy.OnAllocationFailure"/>.
	/// </summary>
	public M68kGcSweepStrategy? GcSweepStrategy { get; init; }

	public M68kGcTelemetryOptions GcTelemetry { get; init; } = new();

	public M68kHeapOptions Heap { get; init; } = new();

	public HunkOutputOptions Hunk { get; init; } = new();

	public KickstartRomOutputOptions Rom { get; init; } = new();

	/// <summary>Absolute addresses for named imports.</summary>
	public IReadOnlyDictionary<string, uint> Imports { get; init; } =
		new ReadOnlyDictionary<string, uint>(new Dictionary<string, uint>());

	/// <summary>Ordered target extensions for external call conventions.</summary>
	public IReadOnlyList<IM68kExternalCallResolver> ExternalCallResolvers { get; init; } =
		Array.Empty<IM68kExternalCallResolver>();
}

