	/// </summary>
	public uint StartAddress { get; init; }

	/// <summary>
	/// Heap size for the compiler runtime's managed pool. Zero means
	/// startup/runtime code must provide the heap range.
	/// </summary>
	public uint Size { get; init; }
}

/// <summary>Options for approximate stale-pressure telemetry in GC runtimes.</summary>
public sealed record M68kGcTelemetryOptions
{
	/// <summary>Approximate stale-pressure bytes that should make allocation trigger GC.</summary>
	public uint StaleBytesThreshold { get; init; }

	/// <summary>Approximate stale-pressure block count that should make allocation trigger GC.</summary>
	public uint StaleBlocksThreshold { get; init; }

	/// <summary>Runtime-defined telemetry sampling interval. Zero selects runtime default.</summary>
	public ushort IntervalTicks { get; init; }
}

/// <summary>Closed-world compilation request.</summary>
public sealed record M68kCompilationRequest
{
	public required string AssemblyPath { get; init; }

	/// <summary>
	/// Additional managed assemblies whose IL method bodies may enter the closed-world
	/// compilation graph. Other references remain metadata-only platform dependencies.
	/// </summary>
	public IReadOnlyList<string> ManagedAssemblyPaths { get; init; } = Array.Empty<string>();

	/// <summary>
	/// Entry selector in <c>Namespace.Type::Method</c> form. When omitted, exactly one
	/// method carrying <see cref="M68kEntryPointAttribute"/> must exist.
	/// </summary>
	public string? EntryPoint { get; init; }

	public M68kCpuTarget Cpu { get; init; } = M68kCpuTarget.M68000;

	/// <summary>
	/// Selects native FPU or bundled software floating-point code generation.
	/// Disabled preserves the historical integer-only compiler behavior.
	/// </summary>
	public M68kFloatingPointMode FloatingPoint { get; init; } =
		M68kFloatingPointMode.Disabled;

	/// <summary>
	/// Controls memory clears. Auto accounts for the MC68000 CLR read cycle: it
	/// reuses an available zero register with MOVE, permits isolated CLR clears of
	/// compiler-owned memory when MOVEQ plus MOVE would not be faster, and enables
	/// CLR for general memory on MC68020 and newer targets. Always explicitly opts
	/// MC68000-compatible general memory into CLR's read-before-write behavior.
	/// </summary>
	public M68kClrPolicy ClrPolicy { get; init; } = M68kClrPolicy.Auto;

	public M68kOutputFormat OutputFormat { get; init; } = M68kOutputFormat.Hunk;

	public M68kRuntimeProfile RuntimeProfile { get; init; } =
		M68kRuntimeProfile.Freestanding;

	/// <summary>
	/// Selects managed exception behavior. Full mode is the default; YOLO is an
	/// explicit compatibility mode for images that retain fatal runtime faults.
	/// </summary>
	public M68kExceptionMode ExceptionMode { get; init; } = M68kExceptionMode.Full;

	/// <summary>
	/// Managed heap policy. When omitted, ROM profile uses no managed heap and
	/// other profiles use the external <see cref="M68kRuntimeImports.Allocate"/>
	/// hook.
	/// </summary>
	public M68kMemoryManagement? MemoryManagement { get; init; }

	/// <summary>
	/// GC sweep trigger. When omitted, GC backends use
	/// <see cref="M68kGcSweepStrategy.OnAllocationFailure"/>.
	/// </summary>
	public M68kGcSweepStrategy? GcSweepStrategy { get; init; }

	public M68kGcTelemetryOptions GcTelemetry { get; init; } = new();

	public M68kHeapOptions Heap { get; init; } = new();

	public HunkOutputOptions Hunk { get; init; } = new();

	public KickstartRomOutputOptions Rom { get; init; } = new();

	/// <summary>Absolute addresses for named imports.</summary>
	public IReadOnlyDictionary<string, uint> Imports { get; init; } =
		new ReadOnlyDictionary<string, uint>(new Dictionary<string, uint>());

	/// <summary>Ordered target extensions for external call conventions.</summary>
	public IReadOnlyList<IM68kExternalCallResolver> ExternalCallResolvers { get; init; } =
		Array.Empty<IM68kExternalCallResolver>();
}

/// <summary>A named range in the linked image.</summary>
public readonly record struct M68kSymbol(string Name, uint Address, int Size);

/// <summary>An absolute 32-bit address patched by the linker.</summary>
public readonly record struct M68kRelocation(int Offset, string Target);

/// <summary>Final linked footprint of one natural loop.</summary>
public sealed record M68kLoopFootprint(
	string Method,
	int HeaderIlOffset,
	uint HeaderAddress,
	int InstructionBytes,
	int SpanBytes,
	int CacheLineCount,
	bool FitsIn256ByteInstructionCache);

/// <summary>Successful compiler output.</summary>
public sealed class M68kCompilationResult
{
	internal M68kCompilationResult(
		byte[] image,
		byte[] code,
		uint entryPoint,
		IReadOnlyList<M68kSymbol> symbols,
		IReadOnlyList<M68kRelocation> relocations,
		string map,
		string? text,
		IReadOnlyList<Backend.M68kMethodAllocationStatistics>
			allocationStatistics,
		IReadOnlyList<Backend.M68kTerminalDeadStoreStatistics>
			terminalDeadStoreStatistics,
		IReadOnlyList<M68kLoopFootprint> loopFootprints,
		IReadOnlyList<string> frameworkFeatures)
	{
		Image = image;
		Code = code;
		EntryPoint = entryPoint;
		Symbols = symbols;
		Relocations = relocations;
		Map = map;
		Text = text;
		AllocationStatistics = allocationStatistics;
		TerminalDeadStoreStatistics = terminalDeadStoreStatistics;
		LoopFootprints = loopFootprints;
		FrameworkFeatures = frameworkFeatures;
	}

	public byte[] Image { get; }

	/// <summary>Linked code before its output container is applied.</summary>
	public byte[] Code { get; }

	public uint EntryPoint { get; }

	public IReadOnlyList<M68kSymbol> Symbols { get; }

	public IReadOnlyList<M68kRelocation> Relocations { get; }

	public string Map { get; }

	/// <summary>Assembler source when <see cref="M68kOutputFormat.Assembly"/> is selected.</summary>
	public string? Text { get; }

	/// <summary>
	/// Natural-loop footprints measured from final linked instruction ranges.
	/// Cache lines use the MC68020/MC68030 256-byte, four-byte-line model.
	/// </summary>
	public IReadOnlyList<M68kLoopFootprint> LoopFootprints { get; }

	/// <summary>Independently linked framework/runtime capabilities.</summary>
	public IReadOnlyList<string> FrameworkFeatures { get; }

	internal IReadOnlyList<Backend.M68kMethodAllocationStatistics>
		AllocationStatistics { get; }

	internal IReadOnlyList<Backend.M68kTerminalDeadStoreStatistics>
		TerminalDeadStoreStatistics { get; }
}
