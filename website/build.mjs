import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';

const website = path.dirname(fileURLToPath(import.meta.url));
const repository = path.dirname(website);
const { values } = parseArgs({ options: { base: { type: 'string', default: '/CopperSharp68k' },
  origin: { type: 'string', default: 'https://ilehtoranta.github.io' } } });
const base = values.base === '/' ? '' : values.base.replace(/\/$/, '');
if (base && (!/^\/[a-zA-Z0-9_/-]+$/.test(base) || base.includes('//')))
  throw new Error('Base must be empty or an absolute URL path with ordinary path segments.');
const origin = new URL(values.origin);
if (!['https:', 'http:'].includes(origin.protocol) || origin.username || origin.password || origin.href !== origin.origin + '/')
  throw new Error('Origin must be an HTTP(S) origin without a path, query, or credentials.');

const scratch = path.join(website, '.build');
const dist = path.join(website, 'dist');
for (const directory of [scratch, dist]) {
  if (fs.existsSync(directory) && (fs.lstatSync(directory).isSymbolicLink() || !fs.lstatSync(directory).isDirectory()))
    throw new Error(`Refusing to replace a symlink or non-directory: ${directory}`);
}
if (fs.existsSync(dist) && !fs.existsSync(path.join(dist, '.coppersharp-generated')))
  throw new Error('website/dist exists without a build marker; move it aside before building.');
fs.mkdirSync(scratch, { recursive: true });
const stage = fs.mkdtempSync(path.join(scratch, 'site-'));
// Rewrite local deployment URLs, preserving GitHub repository/source links.
const replaceBase = text => text
  .replaceAll('https://ilehtoranta.github.io/CopperSharp68k', origin.origin + base)
  .replaceAll('https://coppersharp.dev', origin.origin + base)
  .replace(/(["'(=])\/CopperSharp68k(?=\/|["')?#\s])/g, (_, prefix) => prefix + base);

function copy(source, destination) {
  fs.mkdirSync(destination, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, 'en'))) {
    const from = path.join(source, entry.name);
    const to = path.join(destination, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Source symlink is not supported: ${from}`);
    if (entry.isDirectory()) copy(from, to);
    else if (/\.(html|css|js|txt|xml)$/.test(entry.name)) fs.writeFileSync(to, replaceBase(fs.readFileSync(from, 'utf8')));
    else fs.copyFileSync(from, to);
  }
}

// This helper is used only for disposable builds, never a checkout or recovery archive.
function removeBuild(directory) {
  const resolved = path.resolve(directory);
  if (!resolved.startsWith(scratch + path.sep) || fs.lstatSync(resolved).isSymbolicLink())
    throw new Error(`Refusing to remove a path outside website/.build: ${directory}`);
  fs.rmSync(resolved, { recursive: true });
}

try {
  copy(path.join(website, 'public'), stage);
  copy(path.join(website, 'src/pages'), stage);
  const revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: repository, encoding: 'utf8' }).trim();
  execFileSync(process.env.DOTNET || 'dotnet', ['run', '--project',
    path.join(website, 'ReferenceGenerator/ReferenceGenerator.csproj'), '--configuration', 'Release',
    '--no-launch-profile', '--', repository, stage, base, origin.origin, revision],
  { cwd: repository, stdio: 'inherit' });

  const referencePaths = JSON.parse(fs.readFileSync(path.join(stage, 'reference-paths.json'), 'utf8'));
  fs.unlinkSync(path.join(stage, 'reference-paths.json'));
  const routes = ['/', '/getting-started/', '/compatibility/', ...referencePaths].sort();
  const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
  fs.writeFileSync(path.join(stage, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    routes.map(route => `  <url><loc>${escape(origin.origin + base + route)}</loc></url>`).join('\n') + '\n</urlset>\n');
  fs.writeFileSync(path.join(stage, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${origin.origin}${base}/sitemap.xml\n`);
  fs.writeFileSync(path.join(stage, '.coppersharp-generated'), 'Generated by website/build.mjs\n');
  fs.writeFileSync(path.join(stage, 'build-info.json'), JSON.stringify({ sourceRevision: revision,
    publicationCommit: JSON.parse(fs.readFileSync(path.join(website, 'recovery.json'), 'utf8')).publicationCommit,
    basePath: base, origin: origin.origin }, null, 2) + '\n');

  let previous;
  if (fs.existsSync(dist)) {
    previous = fs.mkdtempSync(path.join(scratch, 'previous-'));
    fs.rmdirSync(previous);
    fs.renameSync(dist, previous);
  }
  try { fs.renameSync(stage, dist); }
  catch (error) { if (previous) fs.renameSync(previous, dist); throw error; }
  if (previous) removeBuild(previous);
  console.log(`Website built in ${dist} (base: ${base || '/'})`);
} finally {
  if (fs.existsSync(stage)) removeBuild(stage);
}
